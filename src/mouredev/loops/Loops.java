package mouredev.loops;

public class Loops {
    public static void main(String[] args) {
        // Loops

        // Bucle for por contador
        for (int i =0; i < 5; i++){
            System.out.println("Hola Java!");
        }

        // ejemplo con array

        String[] names = {"Jose", "Manuel", "Elena"};

        for (int i = 0; i < names.length; i++){
            System.out.println(names[i]);
        }
    }

}
